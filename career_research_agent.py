"""## 3. LoopDetector: يكشف تكرار الوكيل لنفسه"""

@dataclass
class LoopDetectionResult:
    is_looping: bool
    strategy: str  # 'exact', 'fuzzy', 'stagnation', or 'none'
    message: str
    confidence: float


class LoopDetector:
    """Detects loops using exact match, fuzzy match, and output stagnation."""

    def __init__(self, exact_threshold: int = 2, fuzzy_threshold: float = 0.85,
                 stagnation_window: int = 3):
        self.exact_threshold = exact_threshold
        self.fuzzy_threshold = fuzzy_threshold
        self.stagnation_window = stagnation_window
        self.tool_history: list[tuple[str, str]] = []
        self.output_history: list[str] = []

    def _jaccard_similarity(self, s1: str, s2: str) -> float:
        t1, t2 = set(s1.lower().split()), set(s2.lower().split())
        if not t1 and not t2:
            return 1.0
        if not t1 or not t2:
            return 0.0
        return len(t1 & t2) / len(t1 | t2)

    def check_tool_call(self, tool_name: str, tool_input: str) -> LoopDetectionResult:
        current = (tool_name, tool_input.strip())
        exact_count = sum(1 for n, i in self.tool_history if (n, i.strip()) == current)
        if exact_count >= self.exact_threshold:
            self.tool_history.append(current)
            return LoopDetectionResult(
                True, 'exact',
                f"Exact loop: '{tool_name}' called {exact_count + 1} times with identical arguments.",
                1.0)
        recent = self.tool_history[-5:]
        fuzzy = sum(1 for n, i in recent
                    if n == tool_name and self._jaccard_similarity(tool_input, i) >= self.fuzzy_threshold)
        if fuzzy >= self.exact_threshold:
            self.tool_history.append(current)
            return LoopDetectionResult(
                True, 'fuzzy',
                f"Fuzzy loop: '{tool_name}' called {fuzzy + 1} times with very similar arguments.",
                0.85)
        self.tool_history.append(current)
        return LoopDetectionResult(False, 'none', '', 0.0)

    def check_output_stagnation(self, output: str) -> LoopDetectionResult:
        self.output_history.append(output)
        if len(self.output_history) < self.stagnation_window:
            return LoopDetectionResult(False, 'none', '', 0.0)
        recent = self.output_history[-self.stagnation_window:]
        sims = [self._jaccard_similarity(recent[i], recent[j])
                for i in range(len(recent)) for j in range(i + 1, len(recent))]
        avg = sum(sims) / len(sims) if sims else 0.0
        if avg >= self.fuzzy_threshold:
            return LoopDetectionResult(
                True, 'stagnation',
                f'Last {self.stagnation_window} outputs are {avg:.0%} similar: no progress.',
                avg)
        return LoopDetectionResult(False, 'none', '', 0.0)

    def reset(self):
        self.tool_history.clear()
        self.output_history.clear()


# Shared detectors used by the tools and the pipeline below.
tool_detector = LoopDetector(exact_threshold=2, fuzzy_threshold=0.9)  # repeated tool calls
research_detector = LoopDetector(stagnation_window=2)                 # repeated research output
loop_alerts: list[str] = []


def _loop_guard(tool_name: str, tool_input: str):
    """Runs BEFORE a web tool executes. If the agent is repeating itself, the tool is
    skipped and the agent is told to change approach."""
    check = tool_detector.check_tool_call(tool_name, tool_input)
    if check.is_looping:
        loop_alerts.append(f'[{tool_name}] {check.message}')
        print(f'[LoopDetector] {check.message}')
        return (f'LOOP_DETECTED: {check.message} Use a clearly different query, '
                f'or finish with the information you already have.')
    return None

