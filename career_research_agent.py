"""## 9. Pipeline (Graph)مع حلقة"""

MAX_RETRIES = 1


class PipelineState(TypedDict):
    query: str
    thread_id: str
    research: str
    analysis: str
    report: str
    attempts: int
    stalled: bool
    runs: Annotated[list, operator.add]


def _record(stage: str, result: dict) -> dict:
    return {'stage': stage,
            'tokens': result['metadata']['total_tokens'],
            'cost_usd': result['metadata']['cost_usd'],
            'tools': [name for name, _ in result['tool_calls']],
            'search_ok': sum(1 for n, ok in result['tool_results'] if n == 'search_web' and ok),
            'truncated': result['truncated'],
            'failed': result['failed']}


def _seed_search(query: str, attempt: int):
    """Run the web searches ourselves, so the research is grounded even when the model skips tools."""
    if attempt == 0:
        queries = [f'{query} job requirements skills', f'{query} job postings Riyadh Jeddah']
    else:
        queries = [f'{query} required tools frameworks cloud certifications',
                   f'{query} Saudi job description tech stack']
    blocks, ok = [], 0
    for q in queries:
        result = search_web.invoke({'query': q})
        if not result.startswith(BAD_PREFIXES):
            ok += 1
            blocks.append(f'### Search: {q}\n{result}')
    return '\n\n'.join(blocks), ok, len(queries)


async def researcher_node(state: PipelineState) -> dict:
    query = state['query']
    if state['attempts'] > 0:
        query = (
            f"Original request: {state['query']}\n\n"
            'A previous attempt did not produce enough SPECIFIC technical tools. Focus ONLY on finding '
            'concrete, named tools, frameworks, cloud platforms and certifications that appear in real '
            'Saudi job postings. Use different search queries than before.'
        )
    seed_text, seed_ok, seed_total = await asyncio.to_thread(_seed_search, state['query'], state['attempts'])
    if seed_text:
        query += f'\n\nSearch results already collected for you:\n{seed_text}'
    else:
        print('[Search] the pre-search returned nothing; the agent will try the tools itself.')

    result = await safe_run('researcher', researcher, query)
    record = _record('researcher', result)
    record['search_ok'] += seed_ok
    record['tools'] = ['search_web(pre-search)'] * seed_total + record['tools']

    check = research_detector.check_output_stagnation(result['answer'])
    if check.is_looping:
        loop_alerts.append(f'[researcher] {check.message}')
        print(f'[LoopDetector] [researcher] {check.message}')
    return {'research': result['answer'], 'stalled': check.is_looping, 'runs': [record]}


def route_after_researcher(state: PipelineState) -> str:
    if state['stalled']:
        print('[Router]: research did not change, skipping re-analysis and going straight to the writer.')
        return 'writer'
    return 'analyst'


async def analyst_node(state: PipelineState) -> dict:
    prompt = (
        f"Market research:\n{state['research']}\n\n"
        'Task: use search_my_cv to read my real CV, then compare it with this research.'
    )
    result = await safe_run('analyst', analyst, prompt, thread_id=state['thread_id'])
    return {'analysis': result['answer'], 'runs': [_record('analyst', result)]}


async def writer_node(state: PipelineState) -> dict:
    prompt = (
        f"Market research:\n{state['research']}\n\n"
        f"Skill-gap analysis:\n{state['analysis']}"
    )
    if state['attempts'] >= 1:
        prompt += (
            '\n\nThis is a retry after a quality check. Write the plan now using the most specific tools '
            'available above and clearly flag any assumption. Do NOT output NEEDS_SPECIFIC_TOOLS.'
        )
    result = await safe_run('writer', writer, prompt)
    return {'report': result['answer'],
            'attempts': state['attempts'] + 1,
            'runs': [_record('writer', result)]}


def review_condition(state: PipelineState) -> str:
    if state['report'].startswith('[writer failed'):
        return END
    if 'NEEDS_SPECIFIC_TOOLS' in state['report'] and state['attempts'] <= MAX_RETRIES:
        print('\n[Quality Check]: plan is not specific enough.')
        print('[Router]: sending the task back to the researcher...\n')
        return 'researcher'
    return END


graph = StateGraph(PipelineState)
graph.add_node('researcher', researcher_node)
graph.add_node('analyst', analyst_node)
graph.add_node('writer', writer_node)
graph.add_edge(START, 'researcher')
graph.add_conditional_edges('researcher', route_after_researcher,
                            {'analyst': 'analyst', 'writer': 'writer'})
graph.add_edge('analyst', 'writer')
graph.add_conditional_edges('writer', review_condition, {'researcher': 'researcher', END: END})
pipeline = graph.compile()


@observe(name='career_pipeline', as_type='chain')
async def run_pipeline(query: str) -> dict:
    research_detector.reset()
    tool_detector.reset()
    loop_alerts.clear()

    final = await pipeline.ainvoke(
        {'query': query, 'thread_id': f'run-{uuid.uuid4().hex[:8]}', 'research': '', 'analysis': '',
         'report': '', 'attempts': 0, 'stalled': False, 'runs': []},
        config={'recursion_limit': 25},
    )

    runs = final['runs']
    researcher_runs = [r for r in runs if r['stage'] == 'researcher']
    writer_runs = [r for r in runs if r['stage'] == 'writer']
    grounded = any(r['search_ok'] > 0 for r in researcher_runs)
    truncated = bool(writer_runs and writer_runs[-1]['truncated'])
    unresolved = 'NEEDS_SPECIFIC_TOOLS' in final['report']

    plan = final['report'].replace('NEEDS_SPECIFIC_TOOLS', '').strip()
    if not plan:
        plan = 'The agents could not produce a specific plan. Try a more detailed query or CV.'

    notes = []
    if not grounded:
        notes.append('Web search was unavailable or returned nothing: the market requirements below come '
                     'from the model general knowledge, not from verified job postings.')
    if final['stalled']:
        notes.append('The retry research repeated the first one, so the plan is based on limited evidence.')
    if any(r['failed'] for r in runs):
        notes.append('One or more agents failed (for example a rate limit or credit error). '
                     'See the log above, fix it and run again.')
    if truncated:
        notes.append('The plan was cut off by the token limit. Raise MAX_TOKENS and run again.')
    if notes:
        plan = '\n'.join(f'> **Warning:** {n}' for n in notes) + '\n\n' + plan

    tool_names = [t for r in runs for t in r['tools']]
    analyst_calls = [len(r['tools']) for r in runs if r['stage'] == 'analyst']
    researcher_calls = [len(r['tools']) for r in researcher_runs]

    return {
        'answer': plan,
        'metadata': {
            'agent_runs': len(runs),
            'retries_used': final['attempts'] - 1,
            'grounded': grounded,
            'stalled': final['stalled'],
            'truncated': truncated,
            'unresolved': unresolved,
            'search_ok': sum(r['search_ok'] for r in runs),
            'tool_counts': {n: tool_names.count(n) for n in sorted(set(tool_names))},
            'researcher_calls': researcher_calls,
            'analyst_calls': analyst_calls,
            'total_tokens': sum(r['tokens'] for r in runs),
            'total_cost_usd': sum(r['cost_usd'] for r in runs),
            'loop_alerts': list(loop_alerts),
            'within_budget': (all(c <= RESEARCH_TOOL_LIMIT for c in researcher_calls)
                              and sum(analyst_calls) <= ANALYST_TOOL_LIMIT),
        },
    }

