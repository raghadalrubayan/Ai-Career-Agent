logger = logging.getLogger(__name__)
HEADERS = {'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64)'}
BAD_PREFIXES = ('SEARCH_UNAVAILABLE', 'LOOP_DETECTED', 'No results', 'Search failed', 'Error')


def validate_url(url: str) -> bool:
    """Block non-http(s) schemes and private/loopback addresses (SSRF protection)."""
    try:
        parsed = urlparse(url)
        if parsed.scheme not in ('http', 'https') or not parsed.hostname:
            return False
        for info in socket.getaddrinfo(parsed.hostname, None):
            ip = ipaddress.ip_address(info[4][0])
            if ip.is_private or ip.is_loopback or ip.is_link_local or ip.is_reserved or ip.is_multicast:
                return False
        return True
    except Exception:
        return False


def _clean_ddg_link(href: str) -> str:
    if href.startswith('//'):
        href = 'https:' + href
    parsed = urlparse(href)
    if 'duckduckgo.com' in (parsed.netloc or '') and parsed.path.startswith('/l/'):
        target = parse_qs(parsed.query).get('uddg')
        if target:
            return target[0]
    return href


def _search_tavily(query: str, max_results: int):
    from tavily import TavilyClient
    resp = TavilyClient(api_key=TAVILY_API_KEY).search(query, max_results=max_results)
    return [(r.get('title', ''), r.get('url', ''), (r.get('content') or '')[:300])
            for r in resp.get('results', [])]


def _search_ddg(query: str, max_results: int):
    response = requests.post('https://html.duckduckgo.com/html/', data={'q': query},
                             headers=HEADERS, timeout=15)
    response.raise_for_status()
    soup = BeautifulSoup(response.text, 'html.parser')
    hits = []
    for result in soup.find_all('div', class_='result', limit=max_results * 2):
        title_tag = result.find('a', class_='result__a')
        if not title_tag:
            continue
        snippet_tag = result.find('a', class_='result__snippet')
        hits.append((title_tag.get_text(strip=True),
                     _clean_ddg_link(title_tag.get('href', '')),
                     snippet_tag.get_text(strip=True) if snippet_tag else ''))
    return hits


def _format_hits(hits) -> str:
    return '\n\n'.join(f'{i}. {t}\n   Link: {u}\n   Snippet: {s}' for i, (t, u, s) in enumerate(hits, 1))


@tool('search_web')
def search_web(query: str, max_results: int = 5) -> str:
    """Search the web for a query. Returns a list of results with title, link and snippet."""
    blocked = _loop_guard('search_web', query)
    if blocked:
        return blocked
    providers = ([('Tavily', _search_tavily)] if TAVILY_API_KEY else []) + [('DuckDuckGo', _search_ddg)]
    problems = []
    for name, search in providers:
        try:
            hits = [h for h in search(query, max_results) if validate_url(h[1])][:max_results]
            if hits:
                return _format_hits(hits)
            problems.append(f'{name}: no results')
        except Exception as e:
            logger.error(f'{name} search failed: {e}')
            problems.append(f'{name}: {e}')
    return ('SEARCH_UNAVAILABLE: ' + '; '.join(problems) +
            '. Do not invent sources; mark anything you add as general knowledge.')
@tool('read_webpage')
def read_webpage(url: str) -> str:
    """Read the content of a webpage. Returns the text content."""
    blocked = _loop_guard('read_webpage', url)
    if blocked:
        return blocked
    if not validate_url(url):
        return 'Error: Invalid or restricted URL.'
    try:
        response = requests.get(url, headers=HEADERS, timeout=15)
        response.raise_for_status()
        soup = BeautifulSoup(response.text, 'html.parser')
        for el in soup(['script', 'style']):
            el.decompose()
        lines = (line.strip() for line in soup.get_text(separator='\n').splitlines())
        return '\n'.join(line for line in lines if line)[:8000]
    except Exception as e:
        return f'Error reading {url}: {e}'


