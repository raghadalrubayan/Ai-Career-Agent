"""## 5. الـ Runner المشترك: ينفذ الوكيل ويحسب التوكنز والتكلفة وأدوات الاستخدام الفعلية"""

@observe(name='agent_run', as_type='agent')
async def run_agent(agent, query: str, max_steps: int = 10, thread_id: str | None = None) -> dict:
    config = {'recursion_limit': 2 * max_steps + 1}
    if thread_id:
        config['configurable'] = {'thread_id': thread_id}
    try:
        result = await agent.ainvoke({'messages': [('user', query)]}, config=config)
        all_messages = result['messages']
        answer = all_messages[-1].content
        start = max((i for i, m in enumerate(all_messages) if getattr(m, 'type', '') == 'human'), default=0)
        messages = all_messages[start:]
    except GraphRecursionError:
        messages, answer = [], 'Agent stopped: step limit reached.'

    if isinstance(answer, list):
        answer = ''.join(b.get('text', '') if isinstance(b, dict) else str(b) for b in answer)
    if not str(answer).strip():
        answer = '(empty answer)'

    total_tokens = sum((getattr(m, 'usage_metadata', None) or {}).get('total_tokens', 0) for m in messages)
    total_cost = sum(
        float(((getattr(m, 'response_metadata', None) or {}).get('token_usage') or {}).get('cost') or 0)
        for m in messages)
    tool_calls = [(tc['name'], str(tc['args']))
                  for m in messages for tc in (getattr(m, 'tool_calls', None) or [])]
    tool_results = [(getattr(m, 'name', None) or '', not str(getattr(m, 'content', '')).startswith(BAD_PREFIXES))
                    for m in messages if getattr(m, 'type', '') == 'tool']
    last_meta = (getattr(messages[-1], 'response_metadata', None) or {}) if messages else {}
    truncated = last_meta.get('finish_reason') in ('length', 'MAX_TOKENS')

    langfuse_context.update_current_observation(
        usage={'total_tokens': total_tokens}, model=MODEL_NAME,
        metadata={'cost_usd': round(total_cost, 6), 'tool_calls': len(tool_calls)})

    return {'answer': answer, 'tool_calls': tool_calls, 'tool_results': tool_results,
            'truncated': truncated, 'failed': False,
            'metadata': {'total_messages': len(messages), 'total_tokens': total_tokens,
                         'cost_usd': total_cost}}


async def safe_run(stage: str, agent, prompt: str, thread_id: str | None = None) -> dict:
    """A failing agent must not crash the whole pipeline."""
    try:
        return await run_agent(agent, prompt, 10, thread_id)
    except Exception as e:
        print(f'[{stage}] FAILED: {e}')
        return {'answer': f'[{stage} failed: {e}]', 'tool_calls': [], 'tool_results': [],
                'truncated': False, 'failed': True,
                'metadata': {'total_messages': 0, 'total_tokens': 0, 'cost_usd': 0.0}}

